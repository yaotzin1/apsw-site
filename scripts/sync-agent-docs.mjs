/**
 * Renders the operating cycle from `workflow.ai.yml` into `AGENTS.md`, `.agents/rules/workflow_cycle.md`
 * and `GEMINI.md`.
 *
 * `workflow.ai.yml` is the source of truth for the tracks, the stages, the skill registry, the gates
 * and the rules, but no agent toolchain loads it on its own. `AGENTS.md` is what Antigravity and the
 * other AGENTS.md-aware tools read automatically, and `CLAUDE.md` imports it for Claude Code. So the
 * cycle has to be inside AGENTS.md, and it has to be generated rather than retyped: a hand-copied
 * table drifts, and the copy that drifts is the one agents obey.
 *
 * Antigravity reads at most 12,000 characters of any rules file, so AGENTS.md gets what an agent
 * needs before it starts (precedence, tracks, gates, one line per rule) and the cycle file gets the
 * tables (deliverables, stages, skills, required checks, every rule with what enforces it).
 * `scripts/check-workflow.mjs` holds both under the limit.
 *
 *   node scripts/sync-agent-docs.mjs           write the generated files
 *   node scripts/sync-agent-docs.mjs --check   fail if one is stale (hook, CI)
 */

import fs from 'node:fs';
import path from 'node:path';
import { ROOT_DIR, readWorkflow } from './lib/workflow-yaml.mjs';

const TARGET = path.join(ROOT_DIR, 'AGENTS.md');
const CYCLE_FILE = path.join(ROOT_DIR, '.agents', 'rules', 'workflow_cycle.md');
const CYCLE_LINK = '.agents/rules/workflow_cycle.md';
const GEMINI_FILE = path.join(ROOT_DIR, 'GEMINI.md');

const BEGIN = '<!-- BEGIN GENERATED: ai-workflow-cycle (scripts/sync-agent-docs.mjs) -->';
const END = '<!-- END GENERATED: ai-workflow-cycle -->';
const GENERATED_MARKER = '<!-- generated by scripts/sync-agent-docs.mjs -- do not edit -->';

const workflow = readWorkflow();
const governance = workflow.governance ?? {};
const tracks = workflow.tracks ?? [];
const stages = workflow.stages ?? [];
const skills = workflow.skills?.registry ?? [];
const gates = [...(workflow.quality_gates?.pre_commit ?? []), ...(workflow.quality_gates?.commit_msg ?? [])];
const requiredChecks = workflow.ci?.required_checks ?? [];
const rules = workflow.architectural_rules ?? [];
const inherited = workflow.inherited_guidance?.files ?? [];

for (const [label, list] of [['tracks', tracks], ['stages', stages], ['skills.registry', skills], ['quality_gates', gates], ['architectural_rules', rules]]) {
    if (list.length === 0) {
        console.error(`workflow.ai.yml has no ${label}; refusing to generate an empty table.`);
        process.exit(1);
    }
}

const slug = (name) => name.replace(/_/g, '-');
/** Prose from the YAML may name markup like `<script>`, which a Markdown renderer would take for a tag. */
const prose = (text) => String(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\|/g, '\\|');
const code = (values) => values.map((value) => `\`${value}\``).join(', ');
const stageName = new Map(stages.map((stage) => [stage.id, `${stage.phase}. ${stage.name}`]));

/** The first sentence of a rule, which is the rule; the rest is why, and lives in the cycle file. */
const headline = (text) => {
    const first = String(text).split(/(?<=\.)\s/)[0];
    return first.length > 220 ? `${first.slice(0, 217)}...` : first;
};

const block = [
    BEGIN,
    '',
    '> Generated from `workflow.ai.yml`. Do not edit by hand: run `npm run sync`.',
    `> Deliverables per track, the stage and skill tables, and every rule with what enforces it are in \`${CYCLE_LINK}\`.`,
    '',
    '### Precedence',
    '',
    governance.authority ? `**${governance.authority}**` : '',
    '',
    ...(governance.precedence ?? []).map((entry, index) => `${index + 1}. ${entry}`),
    '',
    governance.conflict_resolution ? `On conflict: ${governance.conflict_resolution}` : '',
    '',
    '### Enforced or guidance',
    '',
    'Every statement in this cycle is **enforced** (a hook, a CI job or a script fails when it is broken)',
    'or **guidance** (nothing fails when you do not). The gates, the required checks, the `Track:` trailer',
    'and every rule with a named script are enforced. The stages and every rule marked "review" are',
    'guidance, and exactly as strong as your honesty about following them.',
    '',
    '### Tracks: pick one before starting',
    '',
    'Every commit carries a `Track:` trailer naming one of these. When the work turns out bigger than its',
    'track, move up to the larger track and do the stages it adds. Never move down to skip them.',
    '',
    '| Track | When | Stages |',
    '| :--- | :--- | :--- |',
    ...tracks.map((track) => `| \`${track.id}\` | ${prose(track.when)} | ${track.stages.map((id) => stageName.get(id) ?? id).join('<br>')} |`),
    '',
    '### Blocking gates before a commit',
    '',
    'A real git hook: run `npm run hooks:install` once per clone. `npm run verify` runs the same',
    'gates, and CI runs them on every pull request and push to main.',
    '',
    ...gates.map((gate) => `- **${gate.name}** — \`${gate.command}\``),
    '',
    '### Architectural rules',
    '',
    `One line each. The reason and what enforces it are in \`${CYCLE_LINK}\`.`,
    '',
    ...rules.map((entry) => `- ${prose(headline(entry.rule))}`),
    '',
    END,
].join('\n');

const cycleFile = [
    '# The operating cycle',
    '',
    GENERATED_MARKER,
    '',
    '> Generated from `workflow.ai.yml` by `npm run sync`. `AGENTS.md` carries the precedence, the tracks,',
    '> the gates and one line per rule; this file carries the rest.',
    '',
    '## What each track delivers',
    '',
    '| Track | Deliverables |',
    '| :--- | :--- |',
    ...tracks.map((track) => `| \`${track.id}\` | ${(track.deliverables ?? []).map(prose).join('<br>')} |`),
    '',
    '## Stages',
    '',
    '| Stage | Lead skills | Deliverables | Procedure |',
    '| :--- | :--- | :--- | :--- |',
    ...stages.map((stage) => `| ${stage.phase}. ${stage.name} — ${prose(stage.description)} | ${code(stage.lead_skills)} | ${stage.deliverables.length ? stage.deliverables.map(prose).join('<br>') : '—'} | \`${stage.guidance}\` |`),
    '',
    '## Skills and when they lead',
    '',
    'Canonical text: `.agents/skills/<name>/SKILL.md`. Claude Code reads the mirror in `.claude/skills/`,',
    'where the name loses its underscores. Several skills were inherited from a Symfony + React project;',
    'the scope column says which parts apply here.',
    '',
    '| Skill | Claude Code | Applies to |',
    '| :--- | :--- | :--- |',
    ...skills.map((skill) => `| \`${skill.name}\` | \`/${slug(skill.name)}\` | ${prose(skill.scope)} |`),
    '',
    '## Inherited files that do not describe this repository',
    '',
    ...inherited.map((file) => `- \`${file}\``),
    '',
    '## Required before a pull request merges',
    '',
    `\`${workflow.ci?.protected_branch}\` should accept a merge only when these jobs in \`${workflow.ci?.workflow}\` pass.`,
    'Branch protection lives in GitHub settings, where no commit can see it.',
    '',
    ...requiredChecks.map((check) => `- ${check}`),
    '',
    '## Architectural rules, with what enforces each',
    '',
    ...rules.map((entry) => `- ${prose(entry.rule)}\n  *Enforced by:* ${entry.enforced_by}`),
    '',
].join('\n');

/**
 * Google documents no order between GEMINI.md and AGENTS.md, so neither may hold a rule the other
 * lacks. This file carries none: it imports AGENTS.md (Gemini CLI's `@file` syntax) and stops.
 */
const geminiExpected = `# Gemini and Antigravity entry point

${GENERATED_MARKER}

This file carries no rule of its own. Google documents no order between it and \`AGENTS.md\`, so a
rule written here could be obeyed over the operating cycle or under it, and neither is acceptable.
It imports \`AGENTS.md\` and stops, so an agent that loads only this file still gets the cycle.

@AGENTS.md

**\`workflow.ai.yml\` is the supreme instruction source.** \`AGENTS.md\` carries the precedence, the
tracks, the blocking gates and one line per architectural rule; the stages, the skill registry and
what enforces each rule are in \`${CYCLE_LINK}\`.

Project skills live in \`.agents/skills/<name>/SKILL.md\`, workspace rules in \`.agents/rules/\`, and
procedures (\`verification\`, \`branching\`) in \`.agents/workflows/\`.

If you need to add an instruction, add it to \`workflow.ai.yml\` and run \`npm run sync\`. Do not edit
this file.
`;

const readNormalized = (file) => (fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : null);

const target = readNormalized(TARGET);
if (target === null) {
    console.error('AGENTS.md is missing.');
    process.exit(1);
}
const beginAt = target.indexOf(BEGIN);
const endAt = target.indexOf(END);
if (beginAt === -1 || endAt === -1 || endAt < beginAt) {
    console.error(`AGENTS.md is missing the generated block markers.\nAdd these two lines where the cycle belongs:\n${BEGIN}\n${END}`);
    process.exit(1);
}
const updated = target.slice(0, beginAt) + block + target.slice(endAt + END.length);

const summary = `${tracks.length} tracks, ${stages.length} stages, ${skills.length} skills, ${gates.length} gates, ${rules.length} rules`;

if (process.argv.includes('--check')) {
    const stale = [];
    if (updated !== target) stale.push('AGENTS.md cycle block');
    const cycleActual = readNormalized(CYCLE_FILE);
    if (cycleActual !== cycleFile) stale.push(cycleActual === null ? `${CYCLE_LINK} (missing)` : `${CYCLE_LINK} (stale)`);
    const geminiActual = readNormalized(GEMINI_FILE);
    if (geminiActual !== geminiExpected) stale.push(geminiActual === null ? 'GEMINI.md (missing)' : 'GEMINI.md (stale)');

    if (stale.length > 0) {
        console.error('Out of sync with workflow.ai.yml:');
        for (const entry of stale) console.error(`  - ${entry}`);
        console.error('Run: npm run sync');
        process.exit(1);
    }
    console.log(`AGENTS.md, GEMINI.md and ${CYCLE_LINK} are in sync (${summary})`);
} else {
    fs.writeFileSync(TARGET, updated, 'utf8');
    fs.writeFileSync(CYCLE_FILE, cycleFile, 'utf8');
    fs.writeFileSync(GEMINI_FILE, geminiExpected, 'utf8');
    console.log(`AGENTS.md cycle block, ${CYCLE_LINK} and GEMINI.md written (${summary})`);
}
